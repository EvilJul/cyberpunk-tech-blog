for (const type of ['click', 'change']) {
  document.addEventListener(type, event => {
    const element = event.target.closest(`[data-admin-${type}]`);
    if (element) adminEventHandlers[element.getAttribute(`data-admin-${type}`)]?.call(element, event);
  });
}
document.addEventListener('click', event => {
  const button = event.target.closest('[data-action]');
  if (!button) return;
  const actions = { editArticle, deleteArticle, editCategory, deleteCategory, editTag, deleteTag };
  actions[button.dataset.action]?.(button.dataset.id);
});
