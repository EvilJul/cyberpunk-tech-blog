import test from 'node:test'
import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { mkdtemp, rm, mkdir, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import Database from 'better-sqlite3'
import bcrypt from 'bcrypt'
import sharp from 'sharp'
import { chromium, expect } from 'playwright/test'
import { startFixture } from './helpers/server.js'

/** 用真实隔离后端验收置顶、封面、轮播及子路径；不触及本地文章。 */
test('featured articles and covers work through studio and /blog/ reader', { timeout: 180000 }, async t => {
  const build = await mkdtemp(join(tmpdir(), 'featured-build-'))
  t.after(/* 释放本次临时构建目录。 */ () => rm(build, { recursive: true, force: true }))
  execFileSync(process.execPath, [resolve('node_modules/vite/bin/vite.js'), 'build', '--outDir', build], { env: { ...process.env, VITE_BASE_PATH: '/blog/' }, stdio: 'pipe' })
  const { root, base } = await startFixture(t, 'server/index.js', { BLOG_DIST_DIR: build, VITE_BASE_PATH: '/blog/', NODE_ENV: 'test', SESSION_COOKIE_SECURE: 'false' })
  const db = new Database(join(root, 'blog.db'))
  t.after(/* 关闭隔离数据库。 */ () => db.close())
  db.prepare('INSERT INTO users(id,username,password_hash,role,created_at,updated_at) VALUES(?,?,?,?,1,1)').run('featured-admin', 'featured-admin', await bcrypt.hash('fixture-password-2026', 4), 'admin')
  const browser = await chromium.launch({ headless: true })
  t.after(/* 结束验收浏览器。 */ () => browser.close())
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
  const page = await context.newPage()
  page.setDefaultTimeout(8000)
  const errors = []
  page.on('pageerror', /* 捕获未处理前端异常。 */ error => errors.push(error.message))
  page.on('dialog', /* 接受隔离库中的显式发布确认。 */ dialog => dialog.accept())
  await context.route('https://fonts.googleapis.com/**', /* 避免外部字体影响验收。 */ route => route.fulfill({ body: '', contentType: 'text/css' }))
  const login = await context.request.post(`${base}/blog/api/session/login`, { headers: { Origin: base }, data: { username: 'featured-admin', password: 'fixture-password-2026' } })
  assert.equal(login.status(), 200)
  const session = await (await context.request.get(`${base}/blog/api/session/me`)).json()
  const headers = { Origin: base, 'X-CSRF-Token': session.csrfToken }
  /** 通过真实条件接口创建、发布或修改文章。 */
  async function write(path, method, data, revision) {
    const response = await context.request.fetch(`${base}/blog/api/studio${path}`, { method, headers: { ...headers, ...(revision ? { 'If-Match': `"${revision}"` } : {}) }, data })
    assert.ok(response.ok(), `${path}: ${response.status()} ${await response.text()}`)
    return response.json()
  }
  const image = await sharp({ create: { width: 640, height: 400, channels: 3, background: '#456a89' } }).png().toBuffer()
  const uploaded = await context.request.post(`${base}/blog/api/studio/media`, { headers, multipart: { image: { name: 'cover.png', mimeType: 'image/png', buffer: image } } })
  assert.equal(uploaded.status(), 200, await uploaded.text())
  const mediaResult = await uploaded.json()
  const media = mediaResult.data || mediaResult
  const articles = []
  for (let i = 0; i < 3; i++) {
    let article = await write('/articles', 'POST', { title: `精选文章 ${i + 1}`, content: '## 正文\n\n完整文章内容。', excerpt: '清晰的推荐摘要，介绍这篇文章的实际内容。', cover_media_id: i === 2 ? null : media.id, category: '工程实践' })
    article = await write(`/articles/${article.id}/publish`, 'POST', {}, article.revision)
    if (i < 2) article = await write(`/articles/${article.id}/pin`, 'PUT', { pinned: true }, article.revision)
    articles.push(article)
  }
  // 编辑器封面路径通过真实媒体和草稿／发布接口验收。
  await writeFile(join(root, 'uploads', 'legacy-cover.png'), image)
  await page.goto(`${base}/blog/studio/editor/${articles[2].id}`)
  await page.getByRole('button', { name: '选取封面：legacy-cover.png', exact: true }).click()
  await expect(page.getByAltText('文章封面预览', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '清除封面', exact: true }).click()
  await expect(page.getByText('尚未选择封面', { exact: true })).toBeVisible()
  await page.getByLabel('上传封面', { exact: true }).setInputFiles({ name: 'new-cover.png', mimeType: 'image/png', buffer: image })
  await expect(page.getByAltText('文章封面预览', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '服务端草稿已保存' })).toBeVisible()
  const beforePublish = await (await context.request.get(`${base}/blog/api/articles`)).json()
  assert.equal(beforePublish.data.find(/* 找到刚保存封面的文章快照。 */ item => item.id === articles[2].id).cover_image, null)
  await page.getByRole('button', { name: '发布', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '发布成功' })).toBeVisible()
  const afterPublish = await (await context.request.get(`${base}/blog/api/articles`)).json()
  assert.ok(afterPublish.data.find(/* 验证显式发布后封面可见。 */ item => item.id === articles[2].id).cover_image)
  await page.getByRole('button', { name: '清除封面', exact: true }).click()
  const cleared = page.waitForResponse(/* 等待本次发布完成。 */ response => response.url().endsWith('/publish') && response.request().method() === 'POST')
  await page.getByRole('button', { name: '发布', exact: true }).click()
  assert.equal((await cleared).status(), 200)
  await expect(page.getByRole('status').filter({ hasText: '发布成功' })).toBeVisible()
  await page.goto(`${base}/blog/`)
  const featured = page.getByRole('region', { name: '置顶推荐' })
  await expect(featured).toBeVisible()
  await expect(featured.locator('.article-cover')).toBeVisible()
  assert.ok((await featured.locator('img').getAttribute('src')).includes('/blog/uploads/'))
  await expect.poll(/* 等待真实封面图片解码完成。 */ () => featured.locator('img').evaluate(/* 读取图片加载结果。 */ el => el.complete && el.naturalWidth > 0)).toBe(true)
  await expect(page.locator('.article-card img')).toHaveCount(2)
  assert.ok(!/T\d\d:/.test(await page.locator('.article-card time').first().innerText()), '列表时间应展示为日期')
  const first = await featured.locator('h3').innerText()
  await page.mouse.move(0, 0)
  await expect(featured.locator('h3')).not.toHaveText(first, { timeout: 9000 })
  await featured.hover()
  const hovered = await featured.locator('h3').innerText()
  await page.waitForTimeout(6300)
  await expect(featured.locator('h3')).toHaveText(hovered)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.mouse.move(0, 0)
  await expect(featured.getByRole('button', { name: '播放推荐', exact: true })).toBeDisabled()
  await page.waitForTimeout(6300)
  await expect(featured.locator('h3')).toHaveText(hovered)
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await featured.getByRole('button', { name: '暂停推荐', exact: true }).click()
  await page.getByRole('textbox', { name: '搜索文章', exact: true }).click()
  await page.mouse.move(0, 0)
  const paused = await featured.locator('h3').innerText()
  await page.waitForTimeout(6300)
  await expect(featured.locator('h3')).toHaveText(paused)
  await featured.getByRole('button', { name: '下一篇推荐', exact: true }).click()
  await expect(featured.locator('h3')).not.toHaveText(paused)
  await page.getByRole('textbox', { name: '搜索文章', exact: true }).fill('不存在的关键词')
  await expect(featured).toHaveCount(0)
  await page.goto(`${base}/blog/category/${encodeURIComponent('工程实践')}`)
  await expect(featured).toHaveCount(0)
  await page.goto(`${base}/blog/studio/articles`)
  await page.getByRole('button', { name: '取消置顶', exact: true }).first().click()
  await expect(page.getByRole('button', { name: '取消置顶', exact: true })).toHaveCount(1)
  await page.goto(`${base}/blog/`)
  await expect(featured).toBeVisible()
  await expect(featured.getByRole('button')).toHaveCount(0)
  const href = await featured.locator('a.featured-card').getAttribute('href')
  assert.ok(href.startsWith('/blog/article/'))
  await featured.locator('a.featured-card').click()
  await expect(page).toHaveURL(new RegExp('/blog/article/'))
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(`${base}/blog/`)
  await expect(featured).toBeVisible()
  assert.ok(await page.evaluate(/* 验证移动布局没有横向溢出。 */ () => document.documentElement.scrollWidth <= innerWidth + 1))
  await mkdir(resolve('test-results/featured'), { recursive: true })
  await page.screenshot({ path: resolve('test-results/featured/mobile.png'), fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.screenshot({ path: resolve('test-results/featured/desktop.png'), fullPage: true })
  await page.goto(`${base}/blog/studio/articles`)
  await page.getByRole('button', { name: '取消置顶', exact: true }).click()
  await page.goto(`${base}/blog/`)
  await expect(featured).toHaveCount(0)
  let remaining = await (await context.request.get(`${base}/blog/api/studio/articles/${articles[0].id}`)).json()
  remaining = await write(`/articles/${remaining.id}/pin`, 'PUT', { pinned: true }, remaining.revision)
  db.prepare('UPDATE integration_media SET url=? WHERE id=?').run('/uploads/missing-cover.png', media.id)
  await page.goto(`${base}/blog/`)
  await expect(featured.locator('.article-cover--placeholder')).toBeVisible()
  await expect(page.locator('.article-card img')).toHaveCount(0)
  await page.route('**/blog/api/articles/featured/list', /* 异常推荐条目应被安全丢弃。 */ route => route.fulfill({ json: { data: [null, {}, { id: 'missing-title' }] } }))
  await page.reload()
  await expect(featured).toHaveCount(0)
  assert.deepEqual(errors, [])
})
