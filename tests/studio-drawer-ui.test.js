import test from 'node:test'
import assert from 'node:assert/strict'
import { join, resolve } from 'node:path'
import Database from 'better-sqlite3'
import bcrypt from 'bcrypt'
import { mkdir, writeFile } from 'node:fs/promises'
import { chromium, expect } from 'playwright/test'
import { startFixture } from './helpers/server.js'

/** 使用真实隔离会话验证手机导航方向、动画及各类关闭路径。 */
test('studio mobile drawer enters from left and finishes exit before closing', { timeout: 30000 }, async t => {
  const { root, base } = await startFixture(t, 'server/index.js', { NODE_ENV: 'test', SESSION_COOKIE_SECURE: 'false', BLOG_DIST_DIR: resolve('dist'), VITE_BASE_PATH: '/' })
  const db = new Database(join(root, 'blog.db'))
  t.after(/* 关闭测试数据库。 */ () => db.close())
  db.prepare('INSERT INTO users(id,username,password_hash,role,created_at,updated_at) VALUES(?,?,?,?,1,1)').run('drawer-admin', 'drawer-admin', await bcrypt.hash('drawer-fixture-password', 4), 'admin')
  const browser = await chromium.launch({ headless: true })
  t.after(/* 释放测试浏览器。 */ () => browser.close())
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } })
  const login = await context.request.post(`${base}/api/session/login`, { headers: { Origin: base }, data: { username: 'drawer-admin', password: 'drawer-fixture-password' } })
  assert.equal(login.status(), 200)
  await writeFile(join(root, 'settings.json'), JSON.stringify({ avatar: '/uploads/sidebar-avatar.svg' }))
  const page = await context.newPage()
  await page.route('**/uploads/sidebar-avatar.svg', /* 返回固定头像以验证设置值被实际展示。 */ route => route.fulfill({ contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="80" height="80"><rect width="80" height="80" fill="#41677d"/><circle cx="40" cy="32" r="16" fill="#abd8ed"/></svg>' }))
  page.setDefaultTimeout(5000)
  await page.route('https://fonts.googleapis.com/**', /* 隔离外部字体网络波动。 */ route => route.fulfill({ body: '', contentType: 'text/css' }))
  await page.goto(`${base}/studio`, { waitUntil: 'domcontentloaded' })
  await page.setViewportSize({ width: 1399, height: 776 })
  const sidebar = page.locator('.studio-sidebar')
  await expect(sidebar.locator('.studio-sidebar-heading').getByRole('link', { name: '查看博客' })).toBeVisible()
  await expect(sidebar.locator('.studio-sidebar-footer').getByRole('link', { name: '查看博客' })).toHaveCount(0)
  const avatar = sidebar.getByAltText('账号头像')
  await expect(avatar).toBeVisible()
  assert.equal(await avatar.evaluate(/* 头像应已成功解码而不是空白图片。 */ node => node.complete && node.naturalWidth > 0), true)
  await mkdir('test-results/featured', { recursive: true })
  await page.screenshot({ path: 'test-results/featured/studio-sidebar-profile-desktop.png' })
  await sidebar.getByRole('link', { name: '修改头像', exact: true }).click()
  await expect(page).toHaveURL(/\/studio\/settings$/)
  await expect(page.getByText('作者资料', { exact: true })).toBeVisible()
  await page.goto(`${base}/studio`)
  await page.setViewportSize({ width: 390, height: 844 })
  const trigger = page.getByRole('button', { name: '打开导航', exact: true })
  const drawer = page.getByRole('dialog', { name: '工作台导航', exact: true })
  await trigger.click()
  await expect(drawer).toBeVisible()
  await expect(drawer.getByAltText('账号头像')).toBeVisible()
  await expect(drawer.getByRole('link', { name: '账号设置：drawer-admin' })).toBeVisible()
  assert.ok(await drawer.evaluate(/* 动画即使已结束也应保留其时长，减少时序脆弱性。 */ node => node.getAnimations().some(/* 检查存在真实滑动动画。 */ animation => animation.effect.getTiming().duration === 280)))
  await drawer.evaluate(/* 等待实际动画完成，不靠固定休眠。 */ async node => { await Promise.all(node.getAnimations().map(/* 等待每条抽屉动画。 */ animation => animation.finished)) })
  assert.equal(Math.round((await drawer.boundingBox()).x), 0)
  assert.equal(await page.evaluate(/* 打开模态期间背景不能滚动。 */ () => document.body.style.overflow), 'hidden')
  await page.keyboard.press('Escape')
  await expect(drawer).toHaveAttribute('data-state', 'closing')
  await expect(drawer).not.toBeVisible()
  await expect(trigger).toBeFocused()
  await trigger.click()
  await page.mouse.click(380, 420)
  await expect(drawer).not.toBeVisible()
  await trigger.click()
  await drawer.getByRole('link', { name: '文章', exact: true }).click()
  await expect(page).toHaveURL(/\/studio\/articles$/)
  await expect(drawer).not.toBeVisible()
  await trigger.click()
  await page.setViewportSize({ width: 1280, height: 900 })
  await expect(page.locator('#studio-drawer')).not.toHaveAttribute('open', '')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await trigger.click()
  await expect(drawer).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(drawer).not.toBeVisible()
  assert.equal(await page.evaluate(/* 关闭后恢复打开前的滚动状态。 */ () => document.body.style.overflow), '')
})
