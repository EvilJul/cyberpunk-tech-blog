import test from 'node:test'
import assert from 'node:assert/strict'
import Database from 'better-sqlite3'
import { getOverview } from '../server/services/overviewService.js'

/** 核对北京时间边界、缺失天补零、未来日期排除和草稿口径。 */
test('overview activity uses actual dates and retains cumulative totals', t => {
  const db = new Database(':memory:')
  t.after(/* 释放本次内存数据库。 */ () => db.close())
  db.exec(`CREATE TABLE articles(status TEXT, created_at INTEGER, publish_date TEXT);
    CREATE TABLE categories(id INTEGER); CREATE TABLE tags(id INTEGER);
    CREATE TABLE site_stats(id INTEGER, views INTEGER); INSERT INTO site_stats VALUES(1, 42);`)
  const insert = db.prepare('INSERT INTO articles VALUES(?,?,?)')
  insert.run('published', Date.parse('2026-11-10T16:05:00Z'), '2026-11-10T16:05:00Z')
  insert.run('draft', Date.parse('2026-11-10T15:55:00Z'), null)
  insert.run('published', Date.parse('2026-01-01T00:00:00Z'), '2026-01-01')
  insert.run('published', Date.parse('2026-11-12T00:00:00+08:00'), '2026-11-12')
  insert.run('draft', Date.parse('2026-10-28T23:59:59+08:00'), null)
  const data = getOverview(db, Date.parse('2026-11-11T08:00:00Z'))
  assert.equal(data.articles, 5)
  assert.equal(data.published, 3)
  assert.equal(data.drafts, 2)
  assert.equal(data.views, 42)
  assert.equal(data.activity.length, 14)
  assert.deepEqual(data.activity[0], { date: '2026-10-29', articles: 0, published: 0, drafts: 0 })
  assert.deepEqual(data.activity.at(-1), { date: '2026-11-11', articles: 1, published: 1, drafts: 0 })
  assert.deepEqual(data.activity.at(-2), { date: '2026-11-10', articles: 1, published: 0, drafts: 1 })
  assert.equal(data.activity.reduce(/* 仅统计窗口内真实创建数。 */ (sum, row) => sum + row.articles, 0), 2)
  assert.equal('views' in data.activity[0], false, '无历史访问记录时不得合成访问趋势')
})

/** 通过真实管理员会话验收统计接口与桌面手机图表，并拒绝匿名查询。 */
test('overview metrics render from authenticated actual activity without a visible page header', { timeout: 30000 }, async t => {
  const { startFixture } = await import('./helpers/server.js')
  const { chromium, expect } = await import('playwright/test')
  const { default: bcrypt } = await import('bcrypt')
  const { join, resolve } = await import('node:path')
  const { mkdir } = await import('node:fs/promises')
  const { root, base } = await startFixture(t, 'server/index.js', { BLOG_DIST_DIR: resolve('dist'), VITE_BASE_PATH: '/', NODE_ENV: 'test', SESSION_COOKIE_SECURE: 'false' })
  const db = new Database(join(root, 'blog.db'))
  t.after(/* 关闭隔离数据库。 */ () => db.close())
  db.prepare('INSERT INTO users(id,username,password_hash,role,created_at,updated_at) VALUES(?,?,?,?,1,1)').run('metrics-admin', 'metrics-admin', await bcrypt.hash('metrics-test-password', 4), 'admin')
  const now = Date.now()
  for (let i = 0; i < 4; i++) db.prepare('INSERT INTO articles(id,title,slug,status,created_at,updated_at,publish_date) VALUES(?,?,?,?,?,?,?)').run(`metric-${i}`, `文章 ${i}`, `metric-${i}`, i ? 'published' : 'draft', now - i * 86400000, now, i ? new Date(now - i * 86400000).toISOString() : null)
  const browser = await chromium.launch({ headless: true })
  t.after(/* 关闭验收浏览器。 */ () => browser.close())
  const context = await browser.newContext({ viewport: { width: 1399, height: 776 } })
  assert.equal((await context.request.get(`${base}/api/studio/overview`)).status(), 401)
  const login = await context.request.post(`${base}/api/session/login`, { headers: { Origin: base }, data: { username: 'metrics-admin', password: 'metrics-test-password' } })
  assert.equal(login.status(), 200)
  const response = await context.request.get(`${base}/api/studio/overview`)
  assert.match(response.headers()['cache-control'], /no-store/)
  const data = await response.json()
  assert.equal(data.articles, 4)
  assert.equal(data.activity.reduce(/* 核对近十四天真实新增总数。 */ (sum, row) => sum + row.articles, 0), 4)
  const page = await context.newPage()
  await page.route('https://fonts.googleapis.com/**', /* 排除外部字体网络对验收的影响。 */ route => route.fulfill({ body: '', contentType: 'text/css' }))
  await page.goto(`${base}/studio`, { waitUntil: 'domcontentloaded' })
  await expect(page.locator('.studio-overview .studio-stat-card')).toHaveCount(4)
  await expect(page.locator('.studio-overview .studio-page-header')).toHaveCount(0)
  await expect(page.locator('.studio-activity-chart > svg')).toHaveCount(3)
  await expect(page.getByText('尚无按日访问记录', { exact: true })).toBeVisible()
  await mkdir(resolve('test-results/featured'), { recursive: true })
  await page.screenshot({ path: 'test-results/featured/overview-metrics-desktop.png' })
  await page.locator('.studio-chart-data > summary').first().click()
  await expect(page.locator('.studio-chart-data').first().locator('tbody tr')).toHaveCount(14)
  await page.locator('.studio-chart-data > summary').first().click()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.locator('.studio-overview .studio-stat-card').first()).toBeVisible()
  assert.equal(await page.evaluate(/* 检查手机指标与图表不造成横向滚动。 */ () => document.documentElement.scrollWidth > innerWidth), false)
  await page.screenshot({ path: 'test-results/featured/overview-metrics-mobile.png', fullPage: true })
})
